// islet, so an islet is drawn for its look alone, never sized to hold a node.
//
// A set is traced by geom.py like an island (same shore, sand, rock and terrain
// language, the island's own theme), but nothing in it is scattered: rock blocks
// are the listed `core` rectangles [cx,cy,w,h,deg], sand runs along the listed
// stretch of shore, terrain is the listed polygons. `fragments` are bare rocks
// breaking the surface near an islet: each a few shards [points, tone 0 dark … 4 light],
// the later ones lying on the earlier. A `crag` is one big rock standing out of the
// sea where there is no islet, the summit of a reef ground (seabed.mjs). Every part of
// it is a shape cut for its place, never a rectangle: `base` the low rock awash at the
// waterline (traced like land, so it has a shore), `talus` broken slabs lying on that,
// `body` the rock proper, `slabs` its lighter layers [points, tone], and `sunken` the
// same rock going on under the water [points, step 0 just under the surface … 2 deep].
// It is drawn in the theme's `cragRock` tones, with no dark rim and no dark cracks.
// A `stack` is an islet built like the sky islands round the observatory: one material lying on a
// layer of rock. Its `land` outline is the rock (the waterline), with the game's broad translucent
// dark rim round it as the sky islands have; `slabs` [points, tone] are lighter rock on the ledges;
// `top` is what lies on the rock, 'grass' or 'earth', as its own smaller outline `topPts`, set to
// one side so the rock shows unevenly round it; `patches` [points, shade] lie on the top (grass:
// layer 'a'|'b'|'c'; earth: 'dune'|'duneTop'). Nothing else: an islet is one thing, not a small
// copy of its island.
