//  SEABED  per island: the shelf the island stands on as three depth contours
//          (outer first), and the reefs lying on it. A reef is a few blocks one
//          on another; tier 3 is the deep foot (faintest), tier 1 the top.
//          `lagoon` (optional) is water as shallow as the shore's between pieces
//          of land: the channels of a cracked island.
// Islands open one by one, so each island's floor is drawn with its island.
